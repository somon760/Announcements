import assert from 'node:assert/strict';
import fs from 'node:fs';
import { selectBattles, groupBattles, battleCsv, renderBattleChronicle, renderCompanyHonours } from '../review/battles.js';
const data=JSON.parse(fs.readFileSync(new URL('../review/battles.json',import.meta.url)));
const chapters=JSON.parse(fs.readFileSync(new URL('../review/chapters.json',import.meta.url)));
const all=selectBattles(data),biscuit=selectBattles(data,{company:'biscuit'}),gravy=selectBattles(data,{company:'gravy'}),shared=selectBattles(data,{company:'shared'}),unknown=selectBattles(data,{company:'unassigned'});
assert.equal(new Set(all.map(e=>e.id)).size,data.stats.kills);
assert.equal(biscuit.length+gravy.length-shared.length+unknown.length,all.length);
const ants=selectBattles(data,{family:'Ants'});assert.equal(ants.length,23);assert.equal(groupBattles(ants).length,1);assert.equal(groupBattles(ants,'target').length,5);
assert.equal(groupBattles(ants)[0].variants.get('Giant Ant Behemoth'),8);
assert.equal(selectBattles(data,{company:'gravy',chapter:'bastion'}).length,0);
assert.equal(selectBattles(data,{chapter:'bastion'}).length,11);
assert.equal(selectBattles(data,{query:'ABSOLUTELY NO MATCH'}).length,0);
assert.equal(selectBattles(data,{query:'GLABREZU'}).length,selectBattles(data,{query:'glabrezu'}).length);
assert.equal(groupBattles(all).reduce((n,row)=>n+row.count,0),data.stats.kills);
assert.equal(groupBattles(all).reduce((n,row)=>n+row.xp,0),data.stats.loggedXP);
const csv=battleCsv(groupBattles(ants));assert.match(csv,/'?Giant ant/);assert.match(csv,/"23"/);assert.match(csv,/Brood Medic Swarm: 2/);
const guarded=battleCsv([{label:'=1+1',count:1,xp:0,unknownXP:0,variants:new Map([['Test',1]])}]);assert.match(guarded,/"'=1\+1"/);
const html=renderBattleChronicle(data,chapters);assert.match(html,/The Battle/);assert.match(html,/How the tally works/);
const profile=renderCompanyHonours({company:'Team Gravy'},data,chapters);assert.match(profile,/#\/battle-chronicle\/company\/gravy/);assert.match(profile,/>35</);
console.log('Battle explorer checks passed: shared counting, species variants, filtering, XP, CSV and linked profiles.');
